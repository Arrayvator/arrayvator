def get_hint(expected_token, context=None, source_line=None):
    """Возвращает подсказку для ошибки."""
    key = (expected_token, context)
    if key in SYNTAX_HINTS:
        return SYNTAX_HINTS[key]

    if source_line:
        line_lower = source_line.strip().lower()
        words = line_lower.replace('(', ' ').replace('[', ' ').split()

        for kw, hint in CONTEXT_HINTS.items():
            if kw in words or line_lower.startswith(kw + ' '):
                return hint

        for kw, hint in KEYWORD_HINTS.items():
            if kw in words:
                return hint

    if context == 'FOR':
        return CONTEXT_HINTS['for']
    if context == 'WHILE':
        return CONTEXT_HINTS['while']
    if context == 'IF':
        return CONTEXT_HINTS['if']

    return None


def get_keyword_hint(word):
    """Возвращает подсказку для специального слова."""
    return KEYWORD_HINTS.get(word.lower())