def get_aliases(lang='ru'):
    """Возвращает словарь алиасов для языка."""
    return RU_ALIASES if lang == 'ru' else EN_ALIASES


def get_all_aliases():
    """Все алиасы (RU + EN). При совпадении ключей — RU приоритет."""
    result = dict(EN_ALIASES)
    result.update(RU_ALIASES)
    return result


def find_by_alias(word):
    """
    Ищет функции/служебные слова по алиасу.

    Возвращает список имён (может быть пустым).

    Логика:
        1. Точное совпадение по ключу.
        2. Если нет — поиск по началу ключа (частичное совпадение).
    """
    word = word.lower().strip()
    if not word:
        return []

    all_aliases = get_all_aliases()

    # 1. Точное совпадение
    if word in all_aliases:
        return list(all_aliases[word])

    # 2. Частичное совпадение (начинается с word)
    results = []
    for alias, funcs in all_aliases.items():
        if alias.startswith(word):
            for f in funcs:
                if f not in results:
                    results.append(f)
    return results


